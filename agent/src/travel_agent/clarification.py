# 待办（第 01 课）：从用户旅行需求中识别已知字段。
# 示例输入：
# "下个月想和女朋友去日本玩 5 天，预算 12000，希望轻松一点。"
# 已知字段可能包括 destination、date_range、days、travelers、budget、pace。

# 待办（第 01 课）：计算缺失字段。
# 先关注会阻塞可靠规划的字段：
# - origin：出发城市
# - exact_dates：明确出行日期
# - budget_scope：预算是否包含机票和酒店
# - destination_focus：目的地重点区域
# - visa_or_safety_constraints：相关签证或安全限制

# 待办（第 01 课）：对澄清问题排序。
# 好的第一轮追问最多包含 2-3 个高影响问题。
# 优先询问会影响交通、预算、安全或目的地范围的问题。

# 待办（第 01 课）：追踪对话状态。
# 未来的状态对象应该记录：
# - 已知字段
# - 缺失字段
# - 已经问过的问题
# - 用户回答
# - 当前假设
# - 当前需求是否已经可以进入规划阶段

# 待办（第 01 课）：区分假设和事实。
# 如果用户无法回答某个字段，Agent 可以基于显式假设继续推进，
